  var lang = 'fr';

  function setLang(l) { lang = DICT[l] ? l : 'fr'; }
  function getLang() { return lang; }

  /** Translates a UI key, replacing {placeholders}. */
  function t(key, params) {
    var s = (DICT[lang] && DICT[lang][key]) || DICT.fr[key] || key;
    if (params) {
      s = s.replace(/\{(\w+)\}/g, function (m, k) { return params[k] !== undefined ? params[k] : m; });
    }
    return s;
  }

  /** Picks the current language from a bilingual { fr, en } object. */
  function L(obj) {
    if (obj === null || obj === undefined) return '';
    if (typeof obj === 'string') return obj;
    return obj[lang] || obj.fr || '';
  }

  var I18n = { DICT: DICT, t: t, L: L, setLang: setLang, getLang: getLang };

